#!/usr/bin/env node
/**
 * build-pattern-index.mjs — generate PATTERN-INDEX.md from 05-patterns/*.md
 *
 * Each pattern doc starts with a heading and a blockquote summary. We extract
 * the heading + first paragraph + table of contents into a catalog mirroring
 * COMPONENT-INDEX.md + TOKEN-INDEX.md.
 *
 * v0.14 — R10 patterns expansion (ADR 0030 sibling). The 05-patterns directory
 * now hosts 9 patterns (7 v0.11 baseline + error-pages + email-layout +
 * empty-state-flow). Auto-generation closes the LLM-discovery gap (where the
 * pattern catalog was knowable only by walking the directory).
 *
 * Run with: pnpm pattern-index
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const PATTERNS_DIR = resolve(ROOT, "design-system/05-patterns");

const files = readdirSync(PATTERNS_DIR)
  .filter((f) => f.endsWith(".md") && f !== "README.md")
  .sort();

const patterns = [];
for (const file of files) {
  const content = readFileSync(resolve(PATTERNS_DIR, file), "utf8");
  // Heading: first line starting with `# `
  const headingMatch = content.match(/^# (.+)$/m);
  const heading = headingMatch ? headingMatch[1].trim() : basename(file, ".md");
  // Summary: first blockquote (`> ...`) line
  const summaryMatch = content.match(/^> (.+)$/m);
  const summary = summaryMatch ? summaryMatch[1].trim() : "";
  // Section headings (## level)
  const sectionMatches = [...content.matchAll(/^## (\d+)\.\s+(.+)$/gm)];
  const sections = sectionMatches.map((m) => ({ index: m[1], title: m[2].trim() }));
  patterns.push({ file, heading, summary, sections });
}

// Build markdown
const today = new Date().toISOString().slice(0, 10);
const out = [];
out.push("# PATTERN-INDEX");
out.push("");
out.push(`> Auto-generated by \`pnpm pattern-index\`. Last regenerated: ${today}. Source: \`design-system/05-patterns/*.md\`.`);
out.push("");
out.push(`Lumen ships ${patterns.length} composition patterns at the 05-patterns layer. Patterns are how components compose into shipped UI shapes; they live one tier above the 98-primitive catalog (see \`COMPONENT-INDEX.md\`).`);
out.push("");
out.push("## Pattern catalog");
out.push("");
out.push("| Pattern | Surface category | Use when building |");
out.push("|---|---|---|");
// Map known patterns to surface categories from README
const surfaceCategories = {
  "marketing-landing": "Marketing",
  "saas-dashboard": "Operator",
  "settings-page": "Operator",
  "mobile-primary": "Mobile",
  "ecommerce-product": "E-commerce",
  "auth-flow": "Operator",
  "web-tool": "Operator",
  "error-pages": "All surfaces",
  "email-layout": "Email (transactional + marketing)",
  "empty-state-flow": "All surfaces (Operator + Marketing)",
};
for (const p of patterns) {
  const slug = p.file.replace(/\.md$/, "");
  const surface = surfaceCategories[slug] || "—";
  const useCase = p.summary.length > 110 ? p.summary.slice(0, 110).trim() + "…" : p.summary;
  out.push(`| [${slug}](design-system/05-patterns/${p.file}) | ${surface} | ${useCase.replace(/\|/g, "\\|")} |`);
}
out.push("");
out.push("## Per-pattern section anchors");
out.push("");
for (const p of patterns) {
  const slug = p.file.replace(/\.md$/, "");
  out.push(`### [${slug}](design-system/05-patterns/${p.file})`);
  out.push("");
  if (p.summary) out.push(`> ${p.summary}`);
  out.push("");
  if (p.sections.length) {
    out.push("Sections:");
    for (const s of p.sections) {
      out.push(`- ${s.index}. ${s.title}`);
    }
    out.push("");
  }
}
out.push("");
out.push("## Cross-references");
out.push("");
out.push("- [`COMPONENT-INDEX.md`](./COMPONENT-INDEX.md) — the 98-primitive catalog (one tier below patterns).");
out.push("- [`TOKEN-INDEX.md`](./TOKEN-INDEX.md) — the semantic-token catalog (the wrapper tokens patterns reference).");
out.push("- [`design-system/05-patterns/README.md`](./design-system/05-patterns/README.md) — the pattern doc conventions + voice.");
out.push("- [`USING-LUMEN.md`](./USING-LUMEN.md) — overall consumption guide.");
out.push("");

const outPath = resolve(ROOT, "PATTERN-INDEX.md");
writeFileSync(outPath, out.join("\n"));
console.log(`✓ Wrote ${outPath}`);
console.log(`  ${patterns.length} patterns indexed.`);
